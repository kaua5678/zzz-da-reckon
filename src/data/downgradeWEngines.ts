/**
 * 下位音擎表（用户 2026-10-26：「89 个限定角色带的下位替代，把这些好用的记录成一个表就行了吗，
 * 这样默认就是干净的 01，想找下位也有默认下位表。找不到再启动更重的算法。」）
 *
 * ## 三层，按代价从低到高
 *
 * 1. **角色专属表**（本文件 `DOWNGRADE_WENGINES`）= 实战顶分归档里**真有人穿过**的那几把，
 *    按出现频次降序。命中即直接穿，**0 次伤害求值**。
 * 2. **职业默认表**（`DOWNGRADE_BY_SPECIALTY`）= 该职业全部「不占限定金」音擎，S 在前。
 *    角色没进专属表时用它（仍然是 0 次求值，取第一件）。
 * 3. **按伤害择优**（`downgradeWEngine.wearBestWEngine`）= 前两层都没有候选时才启动，
 *    逐件试穿读全队伤害（每件一次全量求值）。这才是「更重的算法」，不该是缺省路径。
 *
 * ## 口径（为什么这些能进表）
 *
 * - 表里全部是 **不占限定金** 的音擎（A 级 / 常驻 S）——「下位替代」的定义就是「不花金的那件」，
 *   所以穿它 = 0 金，与「基础档 = 干净的 01」自洽。限定音擎不许进表（会凭空计金，
 *   那也是「买金」，属于队伍对比页的加金候选，不是下位）。
 * - **基础档不是下位档**：默认 01 = 每个人都穿自己的推荐专武（主页「配装推荐·一键应用」
 *   同一口径，见 `goldStepsFromCatalog#baseWEngineFor`）。下位是**额外**的一档，
 *   只在用户明确要看「没专武」时才穿（自由对比右位 0 / 队伍对比自动下位开关）。
 * - 来源 = `src/data/teamPresets/*.json` 的历史 `wEngines`（96 条预设 288 槽里 89 槽是
 *   「限定角色故意穿不占金的音擎」）。预设迁到「只带 team」后，这份知识搬到这里保存，
 *   逐条频次见行尾注释（= 该组合在实战收录里出现多少次，出现多的排前面）。
 *
 * ## 为什么不是「按 id 顺序挑第一件」
 *
 * 同职业 A 级之间实测差 3–8 个百分点（`freeCompare/engine.ts#applyCodeToSlot` 的探针记录：
 * 柏妮思 双生泣星 −8.9% / 触电唇彩 −8.6% / 咚哒回声 −16.9%）。表的第一件就是「实战里最常用的那件」，
 * 比 id 顺序靠谱；要更准就往下走第 3 层。
 */
