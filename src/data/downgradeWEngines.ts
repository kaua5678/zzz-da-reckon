/** 下位候选的来源层：命中哪一层决定代价（表 = 0 次求值；null = 没有候选，交给调用方） */
export type DowngradeSource = 'agent' | 'specialty'

/** 解析一个槽位的下位候选：角色表 → 职业表；两层都空 = null（调用方自行决定「更重的算法」或空着） */
export function downgradePoolFor(
  agentId: string | undefined | null,
  specialty: Specialty | undefined,
): { ids: readonly string[]; source: DowngradeSource } | null {
  if (agentId) {
    const own = DOWNGRADE_WENGINES[agentId]
    if (own && own.length > 0) return { ids: own, source: 'agent' }
  }
  if (specialty) {
    const bySpec = DOWNGRADE_BY_SPECIALTY[specialty]
    if (bySpec && bySpec.length > 0) return { ids: bySpec, source: 'specialty' }
  }
  return null
}

/** 缺省下位（表的第一件）；两层都没有 ⇒ null */
export function defaultDowngradeFor(
  agentId: string | undefined | null,
  specialty: Specialty | undefined,
): string | null {
  return downgradePoolFor(agentId, specialty)?.ids[0] ?? null
}
