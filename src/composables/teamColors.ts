/**
 * 稳定哈希 → 色板下标（FNV-1a 32 位）。
 *
 * 为什么不是「按 id 排序后取下标」：那要求每次都拿到**全量** id 清单（页面各处的引用是零散的），
 * 而哈希只用 id 本身，任何调用点都能算出同一个色。纯函数、无状态 ⇒ 可单测。
 */
export function hashColorIndex(id: string, size: number = TEAM_PALETTE.length): number {
  let h = 0x811c9dc5
  for (let i = 0; i < id.length; i++) {
    h ^= id.charCodeAt(i)
    h = Math.imul(h, 0x01000193) >>> 0
  }
  return size > 0 ? h % size : 0
}

/**
 * 勾选清单 → 队伍色表（**顺序即色号**）。
 *
 * 去重而不是让重复项各占一个色号：同一支队在清单里出现两次（父子两处拼出来的清单很常见）
 * 不该把别人的色号往后挤——挤了就会出现「勾了 5 队，第 6 队拿到第 1 队的色」。
 * 超出色板长度按顺序循环（18 色全用完才会撞，此时撞色不可避免）。
 */
export function assignTeamColors(orderedIds: readonly string[]): Record<string, string> {
  const map: Record<string, string> = {}
  let i = 0
  for (const id of orderedIds) {
    if (!id || id in map) continue
    map[id] = TEAM_PALETTE[i % TEAM_PALETTE.length]!
    i++
  }
  return map
}

/** 取某队的色：表内直取；表外（未勾选/已被删）走稳定哈希——**永不返回灰** */
export function teamColorOf(id: string, assigned: Record<string, string>): string {
  const hit = assigned[id]
  if (hit) return hit
  return TEAM_PALETTE[hashColorIndex(id)]!
}
